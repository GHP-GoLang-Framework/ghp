package pages

import (
	"fmt"
	"sort"
	"strings"

	"ghp/src/internal/goimports"
)

// genRoute pairs a ServeMux route with the handler that serves it.
type genRoute struct {
	path    string
	handler string
}

// ghpRoutesTmpl is the fixed skeleton of ghproutes.go. The import block and
// the AddRoutes body are spliced into the two %s slots; NewServer is static.
const ghpRoutesTmpl = `// Code generated by GHP. DO NOT EDIT.

package main

%s

func AddRoutes(mux *http.ServeMux) {
%s}

func NewServer() *http.ServeMux {
	mux := http.NewServeMux()
	AddRoutes(mux)
	return mux
}
`

// GenRoutes returns the Go source for ghproutes.go, which registers every
// page in pages on a ServeMux through AddRoutes. Pages in a subdirectory
// (PkgName other than "main") are imported as <module>/<RelDir> and
// referenced as PkgName.FuncName; pages of the main package live in it and
// are referenced unqualified. Only the GET method is emitted for now.
// Ex: module "example.com/site", blog/[slug].ghp ->
// mux.HandleFunc("GET /blog/{slug}", blog.BlogSlug).
func GenRoutes(pages []*Page, module string) string {
	imports := map[string]bool{}
	routes := make([]genRoute, 0, len(pages))

	for _, p := range pages {
		handler := p.FuncName
		if p.PkgName != "main" {
			handler = p.PkgName + "." + p.FuncName
			imports[module+"/"+p.RelDir] = true
		}
		routes = append(routes, genRoute{p.route(), handler})
	}

	sort.Slice(routes, func(i, j int) bool { return routes[i].path < routes[j].path })

	return fmt.Sprintf(ghpRoutesTmpl, importBlock(imports), routeBlock(routes))
}

// importBlock renders the import declaration of ghproutes.go: net/http for
// the ServeMux handler signature, plus one path per imported subdirectory
// page. The always-present net/http means a site with no subdirectory page
// still gets the one-line form. Ex: {"a/b"} ->
// "import (\n\t\"a/b\"\n\t\"net/http\"\n)".
func importBlock(imports map[string]bool) string {
	specs := make([]goimports.Import, 0, len(imports)+1)
	specs = append(specs, goimports.Import{Path: "net/http"})
	for imp := range imports {
		specs = append(specs, goimports.Import{Path: imp})
	}
	return goimports.Compact(specs)
}

// routeBlock renders one mux.HandleFunc call per route, sorted by path.
// Ex: [{"/about", "About"}] ->
// "\tmux.HandleFunc(\"GET /about\", About)\n".
func routeBlock(routes []genRoute) string {
	lines := make([]string, 0, len(routes))
	for _, r := range routes {
		lines = append(lines, fmt.Sprintf("\tmux.HandleFunc(\"GET %s\", %s)", r.path, r.handler))
	}
	return strings.Join(lines, "\n") + "\n"
}
